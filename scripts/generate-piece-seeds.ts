/**
 * Generates the starting piece templates from chessground's GPL-licensed cburnett
 * set. They only need to be close to a book's pieces, since the classifier adapts
 * to each book afterwards.
 *
 * Run with: npx tsx scripts/generate-piece-seeds.ts
 */
import { createCanvas, loadImage } from '@napi-rs/canvas';
import fs from 'node:fs';

const SIZE = 20;
const css = fs.readFileSync('node_modules/chessground/assets/chessground.cburnett.css', 'utf8');

const roles: Record<string, string> = { pawn: 'p', knight: 'n', bishop: 'b', rook: 'r', queen: 'q', king: 'k' };
const seeds: Record<string, number[]> = {};

for (const [role, letter] of Object.entries(roles)) {
  for (const color of ['white', 'black']) {
    const rule = new RegExp(`\\.cg-wrap piece\\.${role}\\.${color}\\s*\\{\\s*background-image:\\s*url\\('([^']+)'\\)`);
    const match = css.match(rule);
    if (!match) throw new Error(`No image for ${color} ${role}`);

    const image = await loadImage(match[1]!);
    const canvas = createCanvas(SIZE, SIZE);
    const context = canvas.getContext('2d');
    context.fillStyle = '#fff';
    context.fillRect(0, 0, SIZE, SIZE);
    context.drawImage(image, 0, 0, SIZE, SIZE);

    const { data } = context.getImageData(0, 0, SIZE, SIZE);
    const gray: number[] = [];
    for (let i = 0; i < data.length; i += 4) gray.push(Math.round((data[i]! + data[i + 1]! + data[i + 2]!) / 3));
    seeds[color === 'white' ? letter.toUpperCase() : letter] = gray;
  }
}

const body = Object.entries(seeds)
  .map(([label, gray]) => `  ${label}: [${gray.join(',')}],`)
  .join('\n');

fs.writeFileSync(
  'src/vision/pieceSeeds.ts',
  `// Generated by scripts/generate-piece-seeds.ts from chessground's cburnett pieces.
// Each template is ${SIZE} by ${SIZE} grayscale pixels on white.
export const PIECE_SEED_SIZE = ${SIZE};

export const PIECE_SEEDS: Record<string, readonly number[]> = {
${body}
};
`,
);
console.log(`Wrote ${Object.keys(seeds).length} templates`);
